import os
# Paths: REPO is the root of this repository (this file is in tools/). ZARTEX2_SRC is the folder of the Zartex 2 source
# code (the tool these generators read); set the environment variable ZARTEX2_SRC before running them.
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ZARTEX2_SRC = os.environ.get("ZARTEX2_SRC", "Zartex2")
import json, re
m = json.load(open(os.path.join(REPO, r'oracle\api_methods.json')))
best = {}
for o in m:
    if o['class'] != 'LuaMissionScript' or o['ret'] not in ('Node', 'Actor'):
        continue
    n = o['name']
    if n in ('FindPlayerActor', 'GetLogicStart', 'GetActorById', 'GetNodeById'):
        continue
    if n not in best or len(o['params']) > len(best[n]['params']):
        best[n] = o


def default_for(t, d):
    if d is not None:
        d = d.strip()
        if d in ('true', 'false'):
            return d
        if d.startswith('"'):
            return d
        if d in ('null', 'default'):
            return 'nil'
        try:
            float(d.rstrip('fFdDmM'))
            return d.rstrip('fFdDmM')
        except ValueError:
            return '0'
    if t == 'Actor':
        return 'MISSION.GetActor(0)'
    if t == 'Node':
        return 'MISSION.GetNode(0)'
    if t == 'string':
        return '""'
    if t == 'bool':
        return 'false'
    if t == 'Table':
        return '{}'
    return '0'


rows = []
for n, o in sorted(best.items()):
    ps = []
    for p in o['params']:
        d = None
        if '=' in p:
            p, d = [x.strip() for x in p.split('=', 1)]
        t, name = p.rsplit(' ', 1)
        ps.append((t, name, default_for(t, d)))
    rows.append((n, o['ret'], ps))

out = ['//! Generated by gen_creators.py from the LuaMissionScript API: every function that creates an actor or a logic node.',
       '',
       'pub struct Param {',
       '    pub ty: &\'static str,',
       '    pub name: &\'static str,',
       '    pub default: &\'static str,',
       '}',
       '',
       'pub struct Creator {',
       '    pub name: &\'static str,',
       '    pub makes_node: bool,',
       '    pub params: &\'static [Param],',
       '}',
       '',
       'pub const CREATORS: &[Creator] = &[']
for n, r, ps in rows:
    pp = ', '.join('Param { ty: %s, name: %s, default: %s }' % (json.dumps(t), json.dumps(nm), json.dumps(d)) for t, nm, d in ps)
    out.append('    Creator { name: %s, makes_node: %s, params: &[%s] },' % (json.dumps(n), 'true' if r == 'Node' else 'false', pp))
out.append('];')
open(r'..\zartex-core\src\creators.rs', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(len(rows), 'creators;', sum(1 for r in rows if r[1] == 'Actor'), 'actors')
